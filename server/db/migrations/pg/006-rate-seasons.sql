CREATE TABLE IF NOT EXISTS rate_seasons (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text COLLATE "C" NOT NULL,
  start_date   text COLLATE "C",
  end_date     text COLLATE "C",
  weekdays     text COLLATE "C" NOT NULL DEFAULT '',
  room_type_id bigint REFERENCES room_types(id) ON DELETE CASCADE,
  adjust_type  text COLLATE "C" NOT NULL DEFAULT 'percent' CHECK (adjust_type IN ('percent', 'amount')),
  adjust_value bigint NOT NULL DEFAULT 0,
  active       integer NOT NULL DEFAULT 1,
  created_at   text COLLATE "C" NOT NULL
);
ALTER TABLE rate_seasons ENABLE ROW LEVEL SECURITY;
ALTER TABLE reservations ADD COLUMN IF NOT EXISTS night_rates text COLLATE "C";
