-- Twin of ../009-integration-events.sql. Keep webhook metadata isolated from the Supabase Data API.
CREATE TABLE integration_events (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider            text COLLATE "C" NOT NULL,
  external_event_id   text COLLATE "C" NOT NULL,
  event_type          text COLLATE "C" NOT NULL,
  direction           text COLLATE "C" NOT NULL CHECK (direction IN ('inbound', 'outbound')),
  status              text COLLATE "C" NOT NULL,
  received_at         text COLLATE "C" NOT NULL,
  processed_at        text COLLATE "C",
  UNIQUE (provider, external_event_id, direction)
);
CREATE INDEX integration_events_status ON integration_events(status, received_at);
ALTER TABLE integration_events ENABLE ROW LEVEL SECURITY;
