CREATE TABLE IF NOT EXISTS booking_groups (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          text COLLATE "C" NOT NULL UNIQUE,
  name          text COLLATE "C" NOT NULL,
  contact_name  text COLLATE "C" NOT NULL,
  contact_email text COLLATE "C",
  contact_phone text COLLATE "C",
  company       text COLLATE "C",
  gstin         text COLLATE "C",
  notes         text COLLATE "C",
  created_by    bigint REFERENCES users(id) ON DELETE SET NULL,
  created_at    text COLLATE "C" NOT NULL
);
ALTER TABLE booking_groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE reservations ADD COLUMN IF NOT EXISTS group_id bigint REFERENCES booking_groups(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS reservations_group ON reservations(group_id);
