CREATE TABLE IF NOT EXISTS folio_charges (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id bigint NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
  kind           text COLLATE "C" NOT NULL,
  description    text COLLATE "C" NOT NULL,
  sac            text COLLATE "C",
  amount_cents   bigint NOT NULL,
  tax_bp         bigint NOT NULL DEFAULT 0,
  tax_cents      bigint NOT NULL DEFAULT 0,
  posted_by      bigint REFERENCES users(id) ON DELETE SET NULL,
  posted_by_name text COLLATE "C" NOT NULL,
  posted_at      text COLLATE "C" NOT NULL,
  voided_at      text COLLATE "C",
  voided_by_name text COLLATE "C"
);
CREATE INDEX IF NOT EXISTS folio_charges_reservation ON folio_charges(reservation_id);
ALTER TABLE folio_charges ENABLE ROW LEVEL SECURITY;
ALTER TABLE reservations ADD COLUMN IF NOT EXISTS charges_cents bigint NOT NULL DEFAULT 0;
