-- Twin of ../010-payment-attempts.sql. Row-level security keeps attempts out of the Supabase Data API.
CREATE TABLE payment_attempts (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id       bigint NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
  provider             text COLLATE "C" NOT NULL,
  idempotency_key      text COLLATE "C" NOT NULL UNIQUE,
  order_id             text COLLATE "C" NOT NULL UNIQUE,
  provider_payment_id  text COLLATE "C" UNIQUE,
  amount_cents         bigint NOT NULL CHECK (amount_cents > 0),
  currency             text COLLATE "C" NOT NULL,
  status               text COLLATE "C" NOT NULL CHECK (status IN ('creating', 'active', 'success', 'failed', 'expired', 'cancelled', 'review')),
  checkout_url         text COLLATE "C",
  utr                  text COLLATE "C",
  recorded_payment_id  bigint REFERENCES payments(id) ON DELETE SET NULL,
  created_at           text COLLATE "C" NOT NULL,
  updated_at           text COLLATE "C" NOT NULL
);
CREATE INDEX payment_attempts_reservation ON payment_attempts(reservation_id, created_at);
CREATE UNIQUE INDEX payment_attempts_one_open_per_reservation ON payment_attempts(reservation_id) WHERE status IN ('creating', 'active');
ALTER TABLE payment_attempts ENABLE ROW LEVEL SECURITY;
